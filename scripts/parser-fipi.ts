export function parseFipiOfficial(): FipiParseResult {
  const fipiQuestions: any[] = [];
  const sprintQuestions: any[] = [];
  const words: WordEntry[] = [];

  for (const raw of OFFICIAL_FIPI_DATA) {
    const normalized = normalizeRawQuestionToTrainer(raw);
    fipiQuestions.push(normalized.fipiQuestion);
    sprintQuestions.push(...normalized.sprintQuestions);
    words.push(...normalized.words);
  }

  return {
    fipiQuestions,
    sprintQuestions,
    words,
  };
}

