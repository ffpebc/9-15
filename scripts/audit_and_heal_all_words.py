def resolve_letter_and_rule(task, raw_prefix, raw_suffix, context='', full_task_expl='', current_letter=''):
    p = clean_str(raw_prefix)
    s = clean_str(raw_suffix)
    ctx_clean = (clean_str(context) + ' ' + clean_str(full_task_expl)).lower()

    # 1. Homophone check (highest priority for homophone pairs)
    for pattern, kws, cor_l, test_w, wrong_w in HOMOPHONES:
        test_stem = p + '..' + s
        if re.search(pattern, test_stem):
            if any(k in ctx_clean for k in kws):
                rule_text = f'В слове «{p}{cor_l.upper()}{s}» пишется буква «{cor_l.upper()}» ({test_w}). Не путать: {wrong_w}.'
                return cor_l.upper(), 'Проверяемая безударная гласная в корне', rule_text

    # 2. Check full task explanation for exact capital letter
    if full_task_expl:
        cand_regex = r'(?:^|[^\wА-Яа-яЁё])(' + re.escape(p) + r'([А-ЯЁ])' + re.escape(s) + r')(?:[^\wА-Яа-яЁё]|$)'
        m = re.search(cand_regex, full_task_expl)
        if m:
            found_l = m.group(2).upper()
            cand_full = p + ('' if found_l == '—' else found_l.lower()) + s
            if cand_full in dict_words or task in ['10', '11', '12']:
                # Extract detailed teacher sentence if available
                cap_word = m.group(1).strip()
                sent_m = re.search(re.escape(cap_word) + r'\s*—\s*([^.\n]+(?:\.[^.\n]+)?)', full_task_expl)
                rule_expl = sent_m.group(0).strip() if sent_m else f'В слове «{p}{found_l}{s}» пишется буква «{found_l}».'
                topic = 'Орфографическая норма'
                if task == '9': topic = 'Проверяемая безударная гласная в корне'
                elif task == '10': topic = 'Правописание приставок'
                elif task == '11': topic = 'Правописание суффиксов'
                elif task == '12': topic = 'Личные окончания глаголов и суффиксы причастий'
                return found_l, topic, rule_expl

    # 3. Check full task explanation for exact lowercase dictionary word
    if full_task_expl:
        expl_lower = full_task_expl.lower()
        cand_letters = VOWELS_9 if task == '9' else (LETTERS_10 if task == '10' else (LETTERS_11 if task == '11' else LETTERS_12))
        for c in cand_letters:
            cand_w = p + ('' if c == '—' else c) + s
            if cand_w in dict_words and re.search(r'\b' + re.escape(cand_w) + r'\b', expl_lower):
                topic = 'Орфографическая норма'
                if task == '9': topic = 'Проверяемая безударная гласная в корне'
                elif task == '10': topic = 'Правописание приставок'
                elif task == '11': topic = 'Правописание суффиксов'
                elif task == '12': topic = 'Личные окончания глаголов и суффиксы причастий'
                return c.upper(), topic, f'В слове «{p}{c.upper()}{s}» пишется буква «{c.upper()}».'

    # 4. Alternating roots (Task 9)
    if task == '9':
        for pat, cor_l, top, rule_txt in ALTERNATING_RULES:
            for c in VOWELS_9:
                cand_w = p + c + s
                if re.search(pat, cand_w) and (cand_w in dict_words or cand_w.replace('ё', 'е') in dict_words):
                    return cor_l.upper(), top, rule_txt

    # 5. Dictionary resolution
    cand_letters = VOWELS_9 if task == '9' else (LETTERS_10 if task == '10' else (LETTERS_11 if task == '11' else LETTERS_12))
    dict_matches = []
    for c in cand_letters:
        cand_w = p + ('' if c == '—' else c) + s
        if cand_w in dict_words or cand_w.replace('ё', 'е') in dict_words:
            dict_matches.append(c)

    if len(dict_matches) == 1:
        chosen = dict_matches[0].upper()
        topic = 'Орфографическая норма'
        if task == '9': topic = 'Проверяемая безударная гласная в корне'
        elif task == '10': topic = 'Правописание приставок'
        elif task == '11': topic = 'Правописание суффиксов'
        elif task == '12': topic = 'Личные окончания глаголов и суффиксы причастий'
        return chosen, topic, f'В слове «{p}{chosen}{s}» пишется буква «{chosen}».'

    if len(dict_matches) > 1:
        if current_letter and current_letter.lower() in dict_matches:
            if current_letter.upper() not in ['А', 'Р', 'П', 'Н']:
                chosen = current_letter.upper()
                return chosen, 'Орфографическая норма', f'В слове «{p}{chosen}{s}» пишется буква «{chosen}».'
            else:
                non_a = [m for m in dict_matches if m != 'а']
                if non_a:
                    chosen = non_a[0].upper()
                    return chosen, 'Орфографическая норма', f'В слове «{p}{chosen}{s}» пишется буква «{chosen}».'
                return 'А', 'Орфографическая норма', f'В слове «{p}А{s}» пишется буква «А».'
        chosen = dict_matches[0].upper()
        return chosen, 'Орфографическая норма', f'В слове «{p}{chosen}{s}» пишется буква «{chosen}».'

    fallback = current_letter.upper() if current_letter and current_letter not in ['Р', 'П', 'Н'] else ('О' if task == '9' else 'И')
    return fallback, 'Орфографическая норма', f'В слове «{p}{fallback}{s}» пишется буква «{fallback}».'

