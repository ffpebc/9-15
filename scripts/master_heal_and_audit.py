def main():
    print("=" * 70)
    print("RUNNING MASTER HEAL AND AUDIT ENGINE FOR 22K WORDS & TASKS")
    print("=" * 70)

    # 1. Load data
    fipi_path = os.path.join(WORKSPACE_DIR, "src/data/fipiTasksBank9_15.json")
    words_path = os.path.join(WORKSPACE_DIR, "src/data/allWordsBank9_15.json")
    sprint_path = os.path.join(WORKSPACE_DIR, "src/data/sprintBank9_15.json")
