export type ClassifierTaskId = '9' | '10' | '11' | '12' | '13' | '14' | '15';

export interface WordClassification {
  topic: string;
  isTrap: boolean;
  rule: string;
}

export function classifyWordSubtopicAndException(
  task: ClassifierTaskId,
  prefix: string = '',
  suffix: string = '',
  answer: string = '',
  wordExplanation: string = '',
  context: string = '',
  explicitIsTrap?: boolean
): WordClassification {
  const p = prefix.toLowerCase().replace(/\u0301/g, '').replace(/ё/g, 'е').trim();
  const s = suffix.toLowerCase().replace(/\u0301/g, '').replace(/ё/g, 'е').trim();
  const ans = answer.toUpperCase().trim();
  const ansLower = ans === '—' ? '' : ans.toLowerCase().replace(/ё/g, 'е');
  const w = p + ansLower + s;
  const expl = (wordExplanation || '').toLowerCase().replace(/\u0301/g, '').replace(/ё/g, 'е');
  const ctx = (context || '').toLowerCase().replace(/\u0301/g, '').replace(/ё/g, 'е');

  // Remove parenthetical general-rule lists of exceptions so they don't false-trigger on regular words
  const strippedExpl = expl
    .replace(/\(исключени[яе]\s*[:—\-–][^)]*\)/gi, '')
    .replace(/исключени[яе]\s*[:—\-–]\s*(?:некоторые\s+[^)]+|"[^"]+"(?:\s*,\s*"[^"]+")*)/gi, '')
    .replace(/не\s+путать\s+с\s+исключен[^.;)]*/gi, '')
    .replace(/не\s+является\s+исключен[^.;)]*/gi, '')
    .replace(/кроме исключений\s*[:—\-–]?[^)]*/gi, '')
    .replace(/за исключением[^)]*/gi, '');
  const directExplException =
    Boolean(explicitIsTrap) ||
    /исключен/i.test(strippedExpl) ||
    /\bискл\./i.test(strippedExpl) ||
    /\bискл\./i.test(ctx);

  if (task === '9') {
    // 1. -ГАР-/-ГОР-
    const hasGarGorRoot = /(?:гар|гор)/.test(w);
    const isGarGor =
      hasGarGorRoot &&
      (expl.includes('гар/гор') ||
        expl.includes('гор/гар') ||
        expl.includes('-гар-') ||
        expl.includes('-гор-') ||
        (/^(?:вы|из|при|за|у|по|воз|до|об|пере|с|на|раз|про)?г$/.test(p) &&
          /^р(ать|еть|ел|ан|ающ|ар|ок|ки|ь|яч|юч|$)/.test(s))) &&
      !/^(гориз|горист|горделив|горчиц|горд|горе|огорч|гардер|гармон|гарант|гарнир|гарниз|гарпун)/.test(w);
    if (isGarGor) {
      const isExc = /^(выгарк|изгар|пригар)/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -ГАР-/-ГОР-' : 'Чередование корней -ГАР-/-ГОР-',
        isTrap: isExc,
        rule: 'В корнях -ГАР-/-ГОР- под ударением пишется А, без ударения — О (исключения: выгарки, изгарь, пригарь).',
      };
    }

    // 2. -ЗАР-/-ЗОР-
    const hasZarZorRoot = /(?:зар|зор)/.test(w);
    const isZarZor =
      hasZarZorRoot &&
      (expl.includes('зар/зор') ||
        expl.includes('зор/зар') ||
        expl.includes('-зар-') ||
        expl.includes('-зор-') ||
        (/^(?:о|оз|про)?з$/.test(p) && /^(рниц|рницы|рени|рен|рев|рянк|ри|рь|ревой|ревать)/.test(s)));
    if (isZarZor) {
      const isExc = /^(зорев|зорянк)/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -ЗАР-/-ЗОР-' : 'Чередование корней -ЗАР-/-ЗОР-',
        isTrap: isExc,
        rule: 'В корнях -ЗАР-/-ЗОР- без ударения пишется А, под ударением — то, что слышится (исключение: зоревать).',
      };
    }

    // 3. -КАС-/-КОС-
    const hasKasKosRoot = /(?:кас|кос)/.test(w);
    const isKasKos =
      hasKasKosRoot &&
      (expl.includes('кас/кос') ||
        expl.includes('кос/кас') ||
        expl.includes('-кас-') ||
        expl.includes('-кос-') ||
        (/^(?:при|сопри|непри)?к$/.test(p) &&
          /^с(ать|ат|ательн|аем|ну|нов|нут|нувши|нулся)/.test(s))) &&
      !expl.includes('косой') &&
      !expl.includes('косит') &&
      !expl.includes('косые') &&
      !expl.includes('коса');
    if (isKasKos) {
      return {
        topic: 'Чередование корней -КАС-/-КОС-',
        isTrap: false,
        rule: 'В корнях -КАС-/-КОС- пишется А, если за корнем следует суффикс -А- (касательная); иначе пишется О (прикоснуться).',
      };
    }

    // 4. -ЛАГ-/-ЛОЖ-
    const hasLagLozhRoot = /(?:лаг|лож|полог)/.test(w);
    const isLagLozh =
      hasLagLozhRoot &&
      (expl.includes('лаг/лож') ||
        expl.includes('лож/лаг') ||
        expl.includes('-лаг-') ||
        expl.includes('-лож-') ||
        (/^(?:предпо|распо|пред|по|при|из|воз|с|от|на|пере|у|до|об|про|низ|безот|неот)?л$/.test(p) &&
          /^(г|ж)(ать|ает|ающ|аем|аться|ил|ить|ени|енн|ивш|ат|ительн|ител|ност|ение|$)/.test(s)));
    if (isLagLozh) {
      const isExc = w === 'полог' || w.startsWith('полог') || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -ЛАГ-/-ЛОЖ-' : 'Чередование корней -ЛАГ-/-ЛОЖ-',
        isTrap: isExc,
        rule: 'В корнях -ЛАГ-/-ЛОЖ- перед Г пишется А (предполагать), перед Ж — О (предложение). Исключение: полог.',
      };
    }

    // 5. -РАСТ-/-РАЩ-/-РОС-
    const hasRastRosRoot = /(?:раст|ращ|рос|рост|отрасл)/.test(w);
    const isRastRos =
      hasRastRosRoot &&
      (expl.includes('раст/ращ/рос') ||
        expl.includes('рос/раст') ||
        expl.includes('-раст-') ||
        expl.includes('-ращ-') ||
        expl.includes('-рос-') ||
        (/^(?:вы|под|воз|вз|раз|про|за|по|от|на|пере|с|у|водо|дико|ново)?р$/.test(p) &&
          /^(ст|щ|с)(ок|очек|к|ать|и|ущ|енн|ени|ли|ль|л|ший|т|ти|тущ|товщик|тковый)/.test(s))) &&
      !/^(роскош|росси|россып|роспис|розыск|розыгр|роell|раствор|растир|растер|растя|растека|растоп|расторг|расточ|растолк|раask)/.test(w) &&
      !expl.includes('раствор') &&
      !expl.includes('тер/тир');
    if (isRastRos) {
      const isExc =
        /^(?:р[ао]сток|р[ао]сточ|р[ао]стовщ|отрасл|подростк|вырост)/.test(w) ||
        s.startsWith('сток') ||
        s.startsWith('стовщик') ||
        directExplException;
      return {
        topic: isExc
          ? 'Исключение: корень -РАСТ-/-РАЩ-/-РОС-'
          : 'Чередование корней -РАСТ-/-РАЩ-/-РОС-',
        isTrap: isExc,
        rule: 'В корнях -РАСТ-/-РАЩ-/-РОС- перед СТ и Щ пишется А, перед С — О (исключения: росток, ростовщик, отрасль, подростковый, выросток).',
      };
    }

    // 6. -СКАК-/-СКОЧ-
    const hasSkakSkochRoot = /(?:скак|скоч|скач)/.test(w);
    const isSkakSkoch =
      hasSkakSkochRoot &&
      (expl.includes('скак/скоч') ||
        expl.includes('скоч/скак') ||
        expl.includes('-скак-') ||
        expl.includes('-скоч-') ||
        (/^(?:в|вы|за|на|об|от|пере|по|под|при|про|со|у)?ск$/.test(p) && /^(к|ч)/.test(s)));
    if (isSkakSkoch) {
      const isExc = /^(скачок|скачк|скачу|скачи|проскачу)/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -СКАК-/-СКОЧ-' : 'Чередование корней -СКАК-/-СКОЧ-',
        isTrap: isExc,
        rule: 'В корнях -СКАК-/-СКОЧ- перед К пишется А, перед Ч — О (исключения: скачок, скачу).',
      };
    }

    // 7. -МАК-/-МОК-
    const hasMakMokRoot = /(?:мак|мок)/.test(w);
    const isMakMok =
      hasMakMokRoot &&
      (expl.includes('мак/мок') ||
        expl.includes('мок/мак') ||
        expl.includes('-мак-') ||
        expl.includes('-мок-') ||
        (/^(?:об|про|вы|на|непро|в|за|от|пере|по|под|раз)?м$/.test(p) &&
          /^к(ать|нуть|ающ|аем|нув|оkn|нуть|ся|ش|чи)/.test(s)));
    if (isMakMok) {
      return {
        topic: 'Чередование корней -МАК-/-МОК-',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Корень -МАК- пишется в значении «погружать в жидкость» (обмакнуть); -МОК- — «пропускать жидкость, становиться мокрым» (непромокаемый).',
      };
    }

    // 8. -РАВН-/-РОВН-
    const hasRavnRovnRoot = /(?:равн|ровн|уровен|уровн|ровесн|поровн)/.test(w);
    const isRavnRovn =
      hasRavnRovnRoot &&
      (expl.includes('равн/ровн') ||
        expl.includes('ровн/равн') ||
        expl.includes('-равн-') ||
        expl.includes('-ровн-') ||
        (/^(?:с|у|вы|под|раз|по|при|не|равно)?р$/.test(p) && /^вн/.test(s)) ||
        /^(ровесн|уровен|уровн|равнин)/.test(w));
    if (isRavnRovn) {
      const isExc = /^(равнин|ровесн|уровен|уровн|поровн)/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -РАВН-/-РОВН-' : 'Чередование корней -РАВН-/-РОВН-',
        isTrap: isExc,
        rule: 'Корень -РАВН- пишется в значении «равный, одинаковый» (сравнить); -РОВН- — «ровный, гладкий» (выровнять). Исключения: равнина, ровесник, уровень, поровну.',
      };
    }

    // 9. -ТВАР-/-ТВОР-
    const hasTvarTvorRoot = /(?:твар|твор|утвар)/.test(w);
    const isTvarTvor =
      hasTvarTvorRoot &&
      (expl.includes('твар/твор') ||
        expl.includes('твор/твар') ||
        expl.includes('-твар-') ||
        expl.includes('-твор-') ||
        (/^(?:у|со|при|за|вы|на|о|об|от|пере|по|под|пре|раз|рас|благо|миро|живо|чудо|руко|стихо)?тв$/.test(p) &&
          /^р(ь|и|ить|ец|ени|честв|ил|им|ящ|$)/.test(s))) &&
      !expl.includes('отвар') &&
      !expl.includes('варка') &&
      !expl.includes('варит');
    if (isTvarTvor) {
      const isExc = /^утвар/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -ТВАР-/-ТВОР-' : 'Чередование корней -ТВАР-/-ТВОР-',
        isTrap: isExc,
        rule: 'В корнях -ТВАР-/-ТВОР- без ударения пишется О (творить, притвориться), под ударением — то, что слышится. Исключение: утварь.',
      };
    }

    // 10. -КЛАН-/-КЛОН-
    const hasKlanKlonRoot = /(?:клан|клон)/.test(w);
    const isKlanKlon =
      hasKlanKlonRoot &&
      (expl.includes('клан/клон') ||
        expl.includes('клон/клан') ||
        expl.includes('-клан-') ||
        expl.includes('-клон-') ||
        (/^(?:по|на|пре|с|от|у|при|про|непре|коленопре)?кл$/.test(p) && /^н(ить|иться|яться|ени|ен|он|ян)/.test(s)));
    if (isKlanKlon) {
      return {
        topic: 'Чередование корней -КЛАН-/-КЛОН-',
        isTrap: false,
        rule: 'В корнях -КЛАН-/-КЛОН- без ударения пишется О (поклониться, наклониться), под ударением — то, что слышится (кланяться, поклон).',
      };
    }

    // 11. -ПЛАВ-/-ПЛОВ-
    const hasPlavPlovRoot = /(?:плав|плов|плыв)/.test(w);
    const isPlavPlov =
      hasPlavPlovRoot &&
      (expl.includes('плав/плов') ||
        expl.includes('плов/плав') ||
        expl.includes('-плав-') ||
        expl.includes('-плов-') ||
        (/^(?:по|вы|в|за|на|от|пере|под|при|про|рас|с|у|жук-)?пл$/.test(p) && /^в(ец|чих|ок|уч|ать|ник|ни|у|ун)/.test(s)));
    if (isPlavPlov) {
      const isExc = /^(пловец|пловц|пловчих|плывун)/.test(w) || directExplException;
      return {
        topic: isExc ? 'Исключение: корень -ПЛАВ-/-ПЛОВ-' : 'Чередование корней -ПЛАВ-/-ПЛОВ-',
        isTrap: isExc,
        rule: 'В корнях -ПЛАВ-/-ПЛОВ- без ударения пишется А (поплавок, плавучий), кроме слов-исключений: пловец, пловчиха (и плывун).',
      };
    }

    // 12. Чередование Е / И (суффикс -А-) и -ЧЕТ-/-ЧИТ-
    const isChetChitExc = /(?:сочета|четверо|чета)/.test(w) && (expl.includes('чет/чит') || expl.includes('чит/чет') || directExplException);
    if (isChetChitExc) {
      return {
        topic: 'Исключение: корень -ЧЕТ-/-ЧИТ-',
        isTrap: true,
        rule: 'В корнях -ЧЕТ-/-ЧИТ- пишется И перед суффиксом -А- (вычитать), иначе Е (вычесть). Исключения: сочетать, сочетание, словосочетание.',
      };
    }

    const isAlternatingEI =
      expl.includes('бер/бир') ||
      expl.includes('бир/бер') ||
      expl.includes('дер/дир') ||
      expl.includes('дир/дер') ||
      expl.includes('мер/мир') ||
      expl.includes('мир/мер') ||
      expl.includes('пер/пир') ||
      expl.includes('пир/пер') ||
      expl.includes('тер/тир') ||
      expl.includes('тир/тер') ||
      expl.includes('блест/блист') ||
      expl.includes('блист/блест') ||
      expl.includes('жег/жиг') ||
      expl.includes('жиг/жег') ||
      expl.includes('стел/стил') ||
      expl.includes('стил/стел') ||
      expl.includes('чет/чит') ||
      expl.includes('чит/чет') ||
      expl.includes('-бир-') ||
      expl.includes('-бер-') ||
      expl.includes('-мир-') ||
      expl.includes('-мер-') ||
      expl.includes('-тир-') ||
      expl.includes('-тер-') ||
      expl.includes('-пир-') ||
      expl.includes('-пер-') ||
      expl.includes('-жиг-') ||
      expl.includes('-жег-') ||
      expl.includes('-стил-') ||
      expl.includes('-стел-') ||
      expl.includes('-блист-') ||
      expl.includes('-блест-') ||
      expl.includes('-чит-') ||
      expl.includes('-чет-') ||
      (expl.includes('чередован') && (ans === 'Е' || ans === 'И')) ||
      (/^(?:со|у|вы|за|от|под|раз|рас|пере|при|на|об|вз|из|про|до|по|с|не)?(?:б|д|м|п|т|ж|ст|бл|ч)$/.test(p) &&
        /^(?:р|л|г|ст|т)(?:ать|ающ|авш|ая|ани|атель|ат|аем|ть|еть|ел|ереть|ереться|ор|ирать|лить|ев|евш|вши|ший|шая|шее|шие|ло|ли|ла)/.test(s) &&
        !expl.includes('провер') &&
        !expl.includes('←'));
    if (isAlternatingEI) {
      return {
        topic: directExplException
          ? 'Исключение: чередование корней Е / И'
          : 'Чередование корней Е / И (суффикс -А-)',
        isTrap: directExplException,
        rule: 'В корнях с чередованием Е/И (-БЕР-/-БИР-, -МЕР-/-МИР-, -ТЕР-/-ТИР-, -ПЕР-/-ПИР-, -ЖЕГ-/-ЖИГ-, -СТЕЛ-/-СТИЛ-, -ЧЕТ-/-ЧИТ-) пишется И, если за корнем следует суффикс -А-.',
      };
    }

    // 13. Чередование А(Я) / ИМ / ИН
    if (
      expl.includes('им/ин') ||
      expl.includes('-им-') ||
      expl.includes('-ин-') ||
      (/^(?:сж|разж|заж|выж|пож|обж|наж|приж|уж|вз|из|от|под|с|об|при|раз|воспри|предпри|пере|до|за|на|по|про|у|вспом|напом|упом|запом|помин|прокл|закл|нач|поч|зач)$/.test(p) &&
        /^(?:м|н)а/.test(s) &&
        ans === 'И')
    ) {
      return {
        topic: 'Чередование А(Я) с -ИМ-/-ИН- в корне',
        isTrap: false,
        rule: 'В корнях с чередованием А(Я) // ИМ, ИН (сжать — сжимать, начать — начинать, понять — понимать) перед суффиксом -А- пишется ИМ / ИН.',
      };
    }

    // 14. Буквы И / Ы после Ц
    if (p.endsWith('ц') && (ans === 'И' || ans === 'Ы')) {
      const isExc = /^(цыган|цыпл|цыпочк|цыц)/.test(w) || ans === 'Ы' || directExplException;
      return {
        topic: isExc ? 'Исключение: буквы И / Ы после Ц' : 'Буквы И и Ы после Ц в корне',
        isTrap: isExc,
        rule: 'В корнях слов после Ц пишется буква И (цитата, цилиндр, цирк). Исключения: цыган, на цыпочках, цыплёнок, цыкнуть, цыц.',
      };
    }

    // 15. Гласные после шипящих (Ж, Ш, Ч, Щ) в корне (О/Ё и У/Ю)
    if (/[жшчщ]$/.test(p) && (ans === 'Ё' || ans === 'О' || ans === 'Ю' || ans === 'У')) {
      if (ans === 'Ю' || ans === 'У' || /^(брошюр|парашют|жюри)/.test(w)) {
        return {
          topic: 'Исключение: гласные после шипящих в корне',
          isTrap: true,
          rule: 'После шипящих Ж, Ш, Ч, Щ пишутся У, А, но в иноязычных словах-исключениях (брошюра, жюри, парашют) пишется Ю.',
        };
      }
      const isShExc =
        /^(шорох|шоссе|шофер|шоколад|жонглер|жокей|шорт|шов|капюшон|крыжовник|трущоб|мажор|обжор|прожорлив|чопорн|чокнут|чокаться|чащоб|трещотк)/.test(w) ||
        directExplException;
      return {
        topic: isShExc ? 'Исключение: гласные после шипящих в корне' : 'О / Ё после шипящих в корне',
        isTrap: isShExc,
        rule: 'В корне после шипящих под ударением пишется Ё, если есть чередование с Е (чёрный — чернеть, шёпот — шептать). В словарных исключениях (шорох, крыжовник, трущоба, капюшон, жокей) пишется О.',
      };
    }

    // 16. Проверяемая vs Непроверяемая (словарное слово)
    const isUnverifiable =
      expl.includes('непровер') ||
      expl.includes('словарн') ||
      (expl.includes('запомнить') && !expl.includes('провер'));

    if (isUnverifiable) {
      return {
        topic: directExplException
          ? 'Исключение: непроверяемая гласная в корне'
          : 'Словарное слово (непроверяемая в корне)',
        isTrap: directExplException,
        rule: 'Непроверяемая безударная гласная в корне словарного слова не проверяется ударением и требует запоминания по орфографическому словарю ФИПИ.',
      };
    }

    return {
      topic: directExplException
        ? 'Исключение: безударная гласная в корне'
        : 'Проверяемая безударная гласная в корне',
      isTrap: directExplException,
      rule: 'Чтобы проверить безударную гласную в корне, нужно изменить форму слова или подобрать однокоренное слово так, чтобы на эту гласную падало ударение.',
    };
  }

  if (task === '10') {
    // 1. Разделительные Ъ и Ь
    if (ans === 'Ъ' || ans === 'Ь') {
      const isPodyachiy = /^подьяч/.test(w) || (ans === 'Ь' && directExplException);
      if (isPodyachiy) {
        return {
          topic: 'Исключение-ловушка: Ь в корне («подьячий» от «дьяк»)',
          isTrap: true,
          rule: 'В слове «подьячий» (от «дьяк») пишется разделительный Ь в корне, а не Ъ после приставки.',
        };
      }
      return {
        topic: ans === 'Ъ' ? 'Разделительный Ъ после приставок' : 'Разделительный Ь внутри слова',
        isTrap: directExplException,
        rule: 'Разделительный Ъ пишется только после приставок на согласную (и числительных двух-, трёх-, четырёх-) перед буквами Е, Ё, Ю, Я; внутри корня пишется Ь.',
      };
    }

    // 2. Буквы Ы / И после приставок
    if (
      (ans === 'Ы' || ans === 'И') &&
      !p.endsWith('пр') &&
      (expl.includes('после пристав') ||
        expl.includes('после русск') ||
        expl.includes('после иноязычн') ||
        expl.includes('сложносокращ') ||
        expl.includes('взимать') ||
        /^(раз|без|вз|из|с|под|пред|над|об|от|меж|сверх|дез|контр|транс|суб|пан|пост|супер|гипер|интер|спорт|пед|мед|гос|фин)$/.test(p))
    ) {
      if (w.startsWith('взима')) {
        return {
          topic: 'Исключение: глагол «взимать» (сохраняется И)',
          isTrap: true,
          rule: 'Глагол «взимать» — слово-исключение ФИПИ: после русской приставки ВЗ- сохраняется буква И (произносится [взимать]).',
        };
      }
      if (/^(меж|сверх)/.test(p)) {
        return {
          topic: 'Исключение: приставки МЕЖ- и СВЕРХ- (сохраняется И)',
          isTrap: true,
          rule: 'После русских приставок МЕЖ- и СВЕРХ- (межинститутский, сверхизысканный) переход И в Ы не происходит — всегда пишется И.',
        };
      }
      if (/^(дез|контр|транс|суб|пан|пост|супер|гипер|интер)/.test(p) || expl.includes('иноязычн')) {
        return {
          topic: 'Иноязычные приставки (ДЕЗ-, КОНТР-, ТРАНС-, СУБ-)',
          isTrap: false,
          rule: 'После иноязычных приставок (ДЕЗ-, КОНТР-, ПОСТ-, СУБ-, СУПЕР-, ТРАНС-, ПАН-) начальная буква И корня сохраняется.',
        };
      }
      if (/^(спорт|пед|мед|гос|фин|проф|парт|агит)/.test(p) || expl.includes('сложносокращ')) {
        return {
          topic: 'Сложносокращённые слова (сохраняется И)',
          isTrap: false,
          rule: 'В сложносокращённых словах (спортинвентарь, пединститут) во втором корне сохраняется начальная буква И.',
        };
      }
      return {
        topic: 'Буквы Ы и И после приставок на согласную',
        isTrap: false,
        rule: 'После русских приставок на согласную (БЕЗ-, РАЗ-, ПОД-, ПРЕД-, С-, ОТ-, ОБ-) начальная буква И корня меняется на Ы (разыграть, предыстория).',
      };
    }

    // 3. Приставки на -З / -С и двойные приставки НЕ- + С- / ПЕРЕ- + С-
    if (ans === 'З' || ans === 'С') {
      if (
        (p === 'не' && ans === 'С' && /^гор|^добр|^говор|^свят|^счаст|^сказа|^стерп|^смет|^сравн|^сокруш|^сомнен/.test(s)) ||
        (p === 'пере' && ans === 'С' && /^да/.test(s)) ||
        expl.includes('две приставки') ||
        expl.includes('неизменяемая с-')
      ) {
        return {
          topic: 'Исключение-ловушка: двойная приставка НЕ- / ПЕРЕ- + С-',
          isTrap: true,
          rule: 'В словах несгораемый, несдобровать, несговорчивый, пересдать две приставки: НЕ- (или ПЕРЕ-) и неизменяемая приставка С- (приставки З- не бывает).',
        };
      }
      return {
        topic: 'Приставки на -З и -С (перед звонким / глухим)',
        isTrap: Boolean(explicitIsTrap),
        rule: 'В приставках на -З/-С (БЕЗ-/БЕС-, РАЗ-/РАС-, ИЗ-/ИС-, ВЗ-/ВС-, ВОЗ-/ВОС-, ЧРЕЗ-/ЧЕРЕС-) перед звонкими согласными пишется З, перед глухими — С.',
      };
    }

    // 4. Приставки РАЗ-/РАС- и РОЗ-/РОС-
    if ((p === 'р' && /^з|^с/.test(s) && (ans === 'А' || ans === 'О')) || expl.includes('роз/рос')) {
      return {
        topic: 'Гласные А и О в приставках РАЗ-/РАС- и РОЗ-/РОС-',
        isTrap: false,
        rule: 'В приставках РАЗ-/РАС- — РОЗ-/РОС- под ударением пишется О (ро́зыгрыш, ро́спись), без ударения — А (разыгра́ть, расписа́ние).',
      };
    }

    // 5. Приставки ПРА- и ПРО-
    if (p.endsWith('пр') && (ans === 'А' || ans === 'О')) {
      return {
        topic: 'Приставки ПРА- (древность/родство) и ПРО-',
        isTrap: w === 'прообраз' || Boolean(explicitIsTrap),
        rule: 'Приставка ПРА- пишется только в значении древности или прямого родства (прабабушка, прародина, праязык); в остальных случаях — ПРО-.',
      };
    }

    // 6. Неизменяемая приставка ПРЕД-
    if (
      p.endsWith('пр') &&
      ans === 'Е' &&
      /^д/.test(s) &&
      (expl.includes('пред-') ||
        /^(?:не)?пред(взят|защит|прин|остав|полож|полага|угад|упрежд|усмотр|определ|остереж|отврат|ъ|ы|шеств|вестн|седател|ставител|став|приимч|начерта|рассуд|располож)/.test(w))
    ) {
      return {
        topic: 'Неизменяемая приставка ПРЕД-',
        isTrap: false,
        rule: 'Неизменяемая приставка ПРЕД- (ПРЕДО-) всегда пишется с буквой Е (приставки ПРИД- не существует).',
      };
    }

    // 7. Смысловые приставки ПРЕ- и ПРИ-
    if (p.endsWith('пр') && (ans === 'Е' || ans === 'И')) {
      const isDictPrePri =
        expl.includes('словарн') ||
        (expl.includes('запомнить') &&
          !expl.includes('значен') &&
          !expl.includes('очень') &&
          !expl.includes('пере-') &&
          !expl.includes('приближ') &&
          !expl.includes('присоедин') &&
          !expl.includes('неполнот') &&
          !expl.includes('близост'));
      if (isDictPrePri) {
        return {
          topic: 'Словарное слово с ПРЕ- / ПРИ-',
          isTrap: Boolean(explicitIsTrap),
          rule: 'Написание приставок ПРЕ- и ПРИ- в заимствованных и словарных словах (привилегия, приоритет, претензия, пресечь) определяется по словарю ФИПИ.',
        };
      }
      return {
        topic: explicitIsTrap
          ? 'Ловушка ФИПИ: смысловые омофоны ПРЕ- и ПРИ-'
          : 'Смысловые приставки ПРЕ- и ПРИ-',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Приставка ПРЕ- пишется в значении «очень» или «пере-»; ПРИ- — в значениях приближения, присоединения, близости или неполноты действия.',
      };
    }

    return {
      topic: 'Неизменяемые приставки',
      isTrap: false,
      rule: 'Неизменяемые русские приставки (ПО-, ПОД-, НАД-, ОТ-, ОБ-, ЗА-, НА-, ДО-, СО-, ПЕРЕ-, НИЗ-, НИС-) пишутся единообразно независимо от произношения.',
    };
  }

  if (task === '11') {
    // 1. Исключения милостивый, юродивый
    if (/^(милостив|юродив)/.test(w)) {
      return {
        topic: 'Исключение: суффиксы -ИВ- и -ЕВ- (милостивый, юродивый)',
        isTrap: true,
        rule: 'В безударном положении в прилагательных пишется суффикс -ЕВ-, но слова «милостивый» и «юродивый» являются исключениями (пишется -ИВ-).',
      };
    }

    // 2. Неизменяемые суффиксы -ЧИВ- и -ЛИВ- vs ловушки на -ЕВ- после корня на Ч/Л
    if (
      expl.includes('-чив-') ||
      expl.includes('-лив-') ||
      (/[чл]$/.test(p) && /^в(ый|ая|ое|ые|ость|о)$/.test(s))
    ) {
      if (
        /^(гуттаперчев|ключев|грушев|плюшев|грошев|марлев|тюлев|фланелев|магнолиев|алюминиев|гелиев|калиев|натриев|волев|болев|нулев|рулев|целев|солев|полев|долев|щавелев|фасолев|миндалев|вермишелев)/.test(w) ||
        ans === 'Е'
      ) {
        const isTrapWord = /^(гуттаперчев|марлев|тюлев|фланелев)/.test(w) || Boolean(explicitIsTrap);
        return {
          topic: isTrapWord
            ? 'Исключение-ловушка: суффикс -ЕВ- после Ч / Л корня'
            : 'Суффиксы прилагательных -ИВ- и -ЕВ-',
          isTrap: isTrapWord,
          rule: 'Если буква Ч или Л входит в корень (гуттаперч-евый, марл-евый, тюл-евый), то без ударения пишется суффикс -ЕВ-.',
        };
      }
      return {
        topic: 'Неизменяемые суффиксы -ЧИВ- и -ЛИВ-',
        isTrap: false,
        rule: 'В суффиксах прилагательных -ЧИВ- и -ЛИВ- (застенчивый, заботливый) всегда пишется буква И (суффиксов -ЧЕВ-/-ЛЕВ- не существует).',
      };
    }

    // 3. Глаголы перед ударным -ВА- vs -ОВА-/-ЕВА-/-ЫВА-/-ИВА-
    if (
      /^(затмева|продлева|застрева|встрева|намерева|сомнева|увещева|обурева|подозрева|разева|растлева|затева|недоумева|упова)/.test(w) ||
      (expl.includes('ударн') && expl.includes('-ва') && (expl.includes('запомнить') || directExplException))
    ) {
      return {
        topic: 'Исключение: глаголы перед ударным -ВА-',
        isTrap: true,
        rule: 'В глаголах затмевать, продлевать, застревать, намереваться, сомневаться, недоумевать перед ударным суффиксом -ВА- пишется буква Е.',
      };
    }

    if (expl.includes('ударн') && expl.includes('-ва') && !expl.includes('нет ударного -ва')) {
      return {
        topic: 'Глаголы перед ударным суффиксом -ВА-',
        isTrap: false,
        rule: 'Перед ударным суффиксом -ВА- в глаголах сохраняется та же гласная, что и в инфинитиве без -ВА- (овладеть → овладевать, запить → запивать).',
      };
    }

    if (
      expl.includes('-ова-') ||
      expl.includes('-ева-') ||
      expl.includes('-ыва-') ||
      expl.includes('-ива-') ||
      /^ва(ть|ться|я|ющ|вш|ем|л)/.test(s)
    ) {
      return {
        topic: 'Суффиксы глаголов -ОВА-/-ЕВА- и -ЫВА-/-ИВА-',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Если в 1-м лице ед. ч. глагол оканчивается на -УЮ/-ЮЮ, пишется -ОВА-/-ЕВА-; если на -ЫВАЮ/-ИВАЮ — пишется -ЫВА-/-ИВА-.',
      };
    }

    // 4. Суффиксы прилагательных -ИВ- и -ЕВ-
    if (
      /^в(ый|ая|ое|ые|ого|ому|ым|ом|ую|ой|ых|ыми)$/.test(s) ||
      expl.includes('-ев-') ||
      expl.includes('-ив-')
    ) {
      return {
        topic: 'Суффиксы прилагательных -ИВ- и -ЕВ-',
        isTrap: false,
        rule: 'В прилагательных под ударением пишется суффикс -ИВ- (красивый), без ударения — -ЕВ- (сиреневый, ливневый). Исключения: милостивый, юродивый.',
      };
    }

    // 5. Суффиксы прилагательных -К- и -СК-
    if (ans === 'С' || ans === '—' || expl.includes('-ск-') || expl.includes('-к-')) {
      return {
        topic: 'Суффиксы прилагательных -К- и -СК-',
        isTrap: false,
        rule: 'Суффикс -К- пишется у качественных прилагательных (резкий — резок) и после основ на К, Ч, Ц (немецкий, рыбацкий); в остальных случаях — -СК- (французский, матросский).',
      };
    }

    // 6. Неизменяемый суффикс -ЧАТ-
    if (expl.includes('-чат-') || (p.endsWith('ч') && /^т(ый|ая|ое|ые)/.test(s))) {
      return {
        topic: 'Неизменяемый суффикс -ЧАТ-',
        isTrap: false,
        rule: 'Суффикс прилагательных -ЧАТ- (дымчатый, ступенчатый, расплывчатый) всегда пишется с буквой А.',
      };
    }

    // 7. Именные суффиксы (-инк-/-енк-, -ец-/-иц-, -ик-/-ек-, -чик-/-щик-, -еньк-/-оньк-)
    if (
      (ans === 'И' || ans === 'Е') &&
      (expl.includes('-инк-') || expl.includes('-енк-') || /^нк(а|и|у|ой|е)$/.test(s))
    ) {
      return {
        topic: 'Суффиксы существительных -ИНК- и -ЕНК-',
        isTrap: false,
        rule: 'Суффикс -ИНК- пишется в словах, образованных от существительных на -ИНА (горошина → горошинка); в остальных случаях (француженка, вишенка) — -ЕНК-.',
      };
    }
    if (expl.includes('-ец-') || expl.includes('-иц-') || /^ц(а|о|е|ы|у|ей|ем)$/.test(s) || s === 'ц') {
      return {
        topic: 'Суффиксы существительных -ЕЦ- и -ИЦ-',
        isTrap: false,
        rule: 'В мужском роде пишется -ЕЦ- (владелец), в женском — -ИЦ- (метелица); в среднем роде: с ударением на окончании — -ЕЦ- (пальтецо), на основе — -ИЦ- (платьице).',
      };
    }
    if (expl.includes('-ик-') || expl.includes('-ек-')) {
      return {
        topic: 'Суффиксы существительных -ИК- и -ЕК-',
        isTrap: false,
        rule: 'При склонении в суффиксе -ИК- гласная сохраняется (ключик — ключика), а в суффиксе -ЕК- выпадает (замочек — замочка).',
      };
    }
    if (expl.includes('-чик-') || expl.includes('-щик-')) {
      return {
        topic: 'Суффиксы существительных -ЧИК- и -ЩИК-',
        isTrap: false,
        rule: 'После согласных Д, Т, З, С, Ж пишется суффикс -ЧИК- (переводчик, грузчик); после остальных согласных — -ЩИК-.',
      };
    }
    if (expl.includes('-еньк-') || expl.includes('-оньк-') || /^ньк/.test(s)) {
      return {
        topic: 'Суффиксы -ЕНЬК- и -ОНЬК-',
        isTrap: false,
        rule: 'После Г, К, Х пишется суффикс -ОНЬК- (сухонький, тихонький), после остальных согласных — -ЕНЬК- (душенька, тоненький).',
      };
    }

    // 8. Гласная инфинитива перед -ТЬ и -Л-
    if (
      expl.includes('инфинитив') ||
      expl.includes('прошедшего времени') ||
      expl.includes('перед -л-') ||
      /^(ть|ться|лся|лась|лось|лись|л|ла|ло|ли)$/.test(s)
    ) {
      const isExcVerb = directExplException;
      return {
        topic: isExcVerb
          ? 'Исключение: гласная в инфинитиве и прошедшем времени'
          : 'Гласная инфинитива перед -ТЬ и -Л-',
        isTrap: isExcVerb,
        rule: 'Перед суффиксом прошедшего времени -Л- и перед -ТЬ в инфинитиве пишется та же гласная, что и в основе инфинитива (сеять — сеял, клеить — клеил).',
      };
    }

    // 9. О / Ё / Е после шипящих в суффиксах
    if (
      (ans === 'Ё' || ans === 'О' || ans === 'Е') &&
      (/[жшчщ]$/.test(p) || expl.includes('шипящ')) &&
      !expl.includes('-еств-') &&
      !expl.includes('-ет-')
    ) {
      return {
        topic: 'Гласные О / Ё / Е после шипящих в суффиксах',
        isTrap: false,
        rule: 'В суффиксах существительных и прилагательных (не от глаголов) под ударением после шипящих пишется О (ежовый, медвежонок), а в отглагольных словах — Ё (тушёнка, напряжённый).',
      };
    }

    // 10. Суффиксы наречий -А и -О
    if ((s === '' && (ans === 'А' || ans === 'О' || ans === 'У')) || expl.includes('нареч')) {
      return {
        topic: 'Суффиксы наречий -А и -О (правило «окна»)',
        isTrap: false,
        rule: 'В наречиях с приставками ИЗ-, ДО-, С- пишется суффикс -А (изредка, досуха, снова); с приставками В-, НА-, ЗА- — суффикс -О (влево, насухо, запросто).',
      };
    }

    if (/^ветрен/.test(w)) {
      return {
        topic: 'Исключение: прилагательное «ветреный» (суффикс -ЕН-)',
        isTrap: true,
        rule: 'Прилагательное «ветреный» является исключением и пишется с суффиксом -ЕН- (но «безветренный» — с -ЕНН-, а «ветряная мельница» — с -ЯН-).',
      };
    }

    return {
      topic: directExplException
        ? 'Исключение: правописание суффикса'
        : 'Суффиксы существительных и прилагательных',
      isTrap: directExplException,
      rule: 'Правописание суффикса определяется частью речи, ударением и способом словообразования.',
    };
  }

  if (task === '12') {
    // 1. Прошедшее время и страдательные причастия прошедшего времени (перед -ВШ-, -Ш-, -НН-)
    const isPastParticipleOrVerb =
      s.startsWith('вш') ||
      /^нн(ый|ая|ое|ые|ого|ому|ым|ом|ую|ой|ых|ыми|о|ы)$/.test(s) ||
      expl.includes('прошедшего времени') ||
      expl.includes('перед -нн-') ||
      expl.includes('перед суффиксом -нн-') ||
      expl.includes('перед суффиксом -вш-');

    if (isPastParticipleOrVerb) {
      if (s.startsWith('вш')) {
        return {
          topic: directExplException
            ? 'Исключение: причастие прош. вр. (перед -ВШ-)'
            : 'Действительные причастия прош. вр. (перед -ВШ-)',
          isTrap: directExplException,
          rule: 'Перед суффиксом действительного причастия прошедшего времени -ВШ- сохраняется гласная инфинитива перед -ТЬ (увидеть → увидевший, растаять → растаявший).',
        };
      }
      const isHomophoneTrap =
        /^(выкач|закач|накач|подкач|замеш|размеш|вымеш|развеш|навеш|завеш|обвеш|увеш|пристрел|подстрел|отстрел)/.test(w);
      return {
        topic: isHomophoneTrap
          ? 'Ловушка ФИПИ: причастия на -АНН- vs -ЕНН-'
          : 'Страдательные причастия прош. вр. (-АНН-/-ЯНН-/-ЕНН-)',
        isTrap: isHomophoneTrap || Boolean(explicitIsTrap),
        rule: 'В страдательных причастиях прошедшего времени от глаголов на -АТЬ/-ЯТЬ сохраняется А/Я перед -НН- (замешать → замешанный); от глаголов на -ИТЬ/-ЕТЬ пишется -ЕНН- (замесить → замешенный).',
      };
    }

    // 2. Настоящее / будущее время и причастия настоящего времени (зависят от спряжения!)
    if (/^(?:не)?движим/.test(w)) {
      return {
        topic: 'Исключение: причастие на -ИМ- (движимый)',
        isTrap: true,
        rule: 'Причастие «движимый» (и «недвижимый») образовано от старославянского глагола «движити» и является исключением — пишется суффикс -ИМ-.',
      };
    }
    if (/^брезж/.test(w)) {
      return {
        topic: 'Исключение: глагол брезжить (-УЩ-)',
        isTrap: true,
        rule: 'Глагол «брезжить» образует причастие «брезжущий» с суффиксом -УЩ- (исключение).',
      };
    }

    const isConj1Exception =
      (directExplException &&
        !expl.includes('ii спр') &&
        !expl.includes('2 спр') &&
        (expl.includes('i спр') || expl.includes('1 спр'))) ||
      /^(?:по|вы|с|про|за|на|под|пере|рас|у|не)?(?:бре|стел|зижд|зыбл)$/.test(p);
    if (isConj1Exception) {
      return {
        topic: 'Исключение: I спряжение (брить, стелить, зиждиться)',
        isTrap: true,
        rule: 'Глаголы-исключения I спряжения (брить, стелить, зиждиться, зыбиться) имеют личные окончания -ЕШЬ, -ЕТ, -ЕМ, -ЕТЕ, -УТ/-ЮТ и суффиксы причастий -УЩ-/-ЮЩ-, -ЕМ-.',
      };
    }

    const isConj2Exception =
      /^(?:вы|за|из|на|над|о|об|от|пере|по|под|при|про|раз|рас|с|у|в|во|до|недо|пред|со|воз|вос|низ|нис)?(?:гон|держ|дыш|слыш|смотр|вид|ненавид|обид|терп|верт|завис)$/.test(p) ||
      (directExplException && (expl.includes('ii спр') || expl.includes('2 спр')));
    if (isConj2Exception) {
      return {
        topic: 'Исключение: II спряжение (11 глаголов-исключений)',
        isTrap: true,
        rule: '11 глаголов-исключений II спряжения (гнать, держать, дышать, слышать; смотреть, видеть, ненавидеть, обидеть, терпеть, вертеть, зависеть) имеют окончания -ИШЬ, -ИТ, -АТ/-ЯТ и суффиксы -АЩ-/-ЯЩ-, -ИМ-.',
      };
    }

    if (s.startsWith('щ')) {
      return {
        topic: 'Причастия наст. вр. (-УЩ-/-ЮЩ- и -АЩ-/-ЯЩ-)',
        isTrap: Boolean(explicitIsTrap),
        rule: 'В действительных причастиях настоящего времени от глаголов I спряжения пишутся суффиксы -УЩ-/-ЮЩ-, от глаголов II спряжения — -АЩ-/-ЯЩ-.',
      };
    }

    if (s.startsWith('м')) {
      return {
        topic: 'Страдательные причастия наст. вр. (-ЕМ- и -ИМ-)',
        isTrap: Boolean(explicitIsTrap),
        rule: 'В страдательных причастиях настоящего времени от глаголов I спряжения пишется суффикс -ЕМ-, от глаголов II спряжения — -ИМ-.',
      };
    }

    return {
      topic: 'Личные окончания глаголов (I и II спряжение)',
      isTrap: Boolean(explicitIsTrap),
      rule: 'В личных окончаниях глаголов I спряжения пишутся буквы Е, У, Ю; у глаголов II спряжения (на -ИТЬ) — буквы И, А, Я.',
    };
  }

  if (task === '13') {
    if (
      (s.startsWith('смотря') || s.startsWith('взирая')) &&
      (ans === 'СЛИТНО' || ctx.includes('смотря на') || ctx.includes('взирая на') || expl.includes('предлог'))
    ) {
      return {
        topic: 'Исключение: предлог «несмотря на / невзирая на»',
        isTrap: true,
        rule: 'Производные предлоги «несмотря на» и «невзирая на» (в значении «вопреки») всегда пишутся с НЕ слитно; деепричастие «не смотря по сторонам» (не глядя) — раздельно.',
      };
    }

    if (
      expl.includes('без не ') ||
      expl.includes('без частицы не') ||
      /^(году|годова|доумев|взлюб|навид|истов|леп|рях|вежд|веж|брежн|уклюж|избежн|утомим|поколебим|скончаем|иссякаем|сокрушим|отъемлем|приступн|стерпим|удержим|вредим|победим|уязвим|постижим|изгладим|одолим|отразим|угасим)/.test(s)
    ) {
      return {
        topic: 'Исключение: без НЕ не употребляется (слитно)',
        isTrap: true,
        rule: 'Слова любой части речи, которые не употребляются без НЕ (негодуя, нелепый, неизбежный, невзлюбить), всегда пишутся с НЕ слитно.',
      };
    }

    if (
      (s.startsWith('до') || w.startsWith('недо')) &&
      (expl.includes('недо-') || expl.includes('не до конца') || expl.includes('не завершен') || expl.includes('дотягива') || ans === 'СЛИТНО')
    ) {
      return {
        topic: 'Ловушка: приставка НЕДО- (нехватка) vs НЕ ДО-',
        isTrap: true,
        rule: 'Приставка НЕДО- со значением неполноты, нехватки по сравнению с нормой (недостаёт терпения, недоедать) пишется слитно; действие, не доведённое до конца (не досмотрел фильм) — раздельно.',
      };
    }

    if (expl.includes('категории состояния') || /^(рад|должен|готов|намерен|обязан|способн|согласн|прав|виноват)$/.test(s)) {
      return {
        topic: 'Слова категории состояния с НЕ (всегда раздельно)',
        isTrap: true,
        rule: 'С краткими прилагательными и словами категории состояния (не рад, не должен, не готов, не намерен, не обязан) частица НЕ всегда пишется раздельно.',
      };
    }

    if (expl.includes('деепричастие') || /^(смотря|взирая|читая|говоря|понимая|замечая|осознавая|принимая)/.test(s)) {
      return {
        topic: 'Правописание НЕ с деепричастиями',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Частица НЕ с деепричастиями пишется раздельно (кроме слов, которые без НЕ не употребляются: негодуя, недоумевая, и предлогов несмотря на / невзирая на).',
      };
    }

    if (expl.includes('краткое причастие') || /^(проверена|решена|окончен|выполнены|измерен|обозлен|скрыты|сделана)$/.test(s)) {
      return {
        topic: 'Краткие причастия с НЕ (всегда раздельно)',
        isTrap: Boolean(explicitIsTrap),
        rule: 'С краткими страдательными причастиями (не прочитана, не скрыты, не обозлён) частица НЕ всегда пишется раздельно.',
      };
    }

    if (expl.includes('причастие')) {
      const hasDep = expl.includes('зависим') || ans === 'РАЗДЕЛЬНО';
      return {
        topic: hasDep
          ? 'Полные причастия с зависимыми словами (раздельно)'
          : 'Одиночные полные причастия с НЕ (слитно)',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Полные причастия пишутся с НЕ раздельно при наличии зависимых слов или противопоставления с союзом А; одиночные полные причастия пишутся с НЕ слитно.',
      };
    }

    if (expl.includes('прилагательн') || expl.includes('противопоставлен') || expl.includes('отнюдь')) {
      return {
        topic: 'Правописание НЕ с прилагательными',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Прилагательные с НЕ пишутся слитно, если можно подобрать синоним без НЕ и нет противопоставления с союзом А или слов далеко не, вовсе не, отнюдь не.',
      };
    }

    if (expl.includes('наречи')) {
      return {
        topic: 'Правописание НЕ и НИ с наречиями',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Наречия на -О/-Е пишутся с НЕ слитно при отсутствии противопоставления с А и усилительных слов; отрицательные наречия (негде, незачем, никуда) пишутся слитно.',
      };
    }

    if (expl.includes('местоимен')) {
      return {
        topic: 'Правописание НЕ и НИ с местоимениями',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Отрицательные и неопределённые местоимения без предлога пишутся слитно (некого, никто), а при наличии предлога — в три слова (не у кого, ни с кем).',
      };
    }

    if (expl.includes('существительн')) {
      return {
        topic: 'Правописание НЕ с существительными',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Существительные пишутся с НЕ слитно, если образуют новое понятие (неправда = ложь), и раздельно при противопоставлении с союзом А.',
      };
    }

    if (expl.includes('глагол')) {
      return {
        topic: 'Правописание НЕ и НИ с глаголами',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Частицы НЕ и НИ с глаголами всегда пишутся раздельно (кроме глаголов без НЕ: негодовать, невзлюбить, и глаголов с приставкой НЕДО-).',
      };
    }

    return {
      topic: 'Слитное и раздельное написание НЕ и НИ',
      isTrap: Boolean(explicitIsTrap),
      rule: 'Правописание НЕ и НИ определяется частью речи, наличием зависимых слов, противопоставления с союзом А или усилительных слов (далеко не, вовсе не, отнюдь не).',
    };
  }

  if (task === '14') {
    if (expl.includes('чтобы') || expl.includes('также') || expl.includes('тоже') || expl.includes('зато') || expl.includes('притом') || expl.includes('причем')) {
      const isHomo = expl.includes('местоимен') || expl.includes('частиц') || expl.includes('предлог');
      return {
        topic: isHomo ? 'Союз vs омонимичное местоимение / частица' : 'Сочинительные и подчинительные союзы',
        isTrap: isHomo,
        rule: 'Союзы чтобы, также, тоже, зато, притом, причём пишутся слитно; местоимения с частицами или предлогами (что бы, так же, то же, за то, при том) — раздельно.',
      };
    }
    if (expl.includes('предлог') || expl.includes('в течение') || expl.includes('в продолжение') || expl.includes('ввиду') || expl.includes('вследствие') || expl.includes('наподобие')) {
      const isExc = expl.includes('иметь в виду') || expl.includes('в течении') || expl.includes('в продолжении') || expl.includes('в следствии');
      return {
        topic: isExc ? 'Ловушка: предлог vs существительное с предлогом' : 'Производные предлоги',
        isTrap: isExc,
        rule: 'Производные предлоги ввиду, вследствие, наподобие, вроде, вместо, навстречу, насчёт пишутся слитно; в течение, в продолжение, в заключение, в виде, в связи с — всегда раздельно.',
      };
    }
    if (expl.includes('пол-') || expl.includes('юли') || expl.includes('полу-')) {
      const isExc = ans === 'ДЕФИСНО' || w.includes('пол-');
      return {
        topic: isExc ? 'Корень ПОЛ- (Правило ЮЛИ)' : 'Корень ПОЛ- и приставка ПОЛУ-',
        isTrap: isExc,
        rule: 'Корень ПОЛ- пишется через дефис перед гласными, буквой Л и прописными буквами (ЮЛЯ: пол-яблока, пол-лимона, пол-Москвы); в остальных случаях слитно (полчаса). ПОЛУ- всегда слитно.',
      };
    }
    if (expl.includes('наречи') || expl.includes('по-') || expl.includes('дефис')) {
      return {
        topic: 'Слитное, дефисное и раздельное написание наречий',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Наречия с приставкой ПО- на -ОМУ/-ЕМУ/-СКИ/-ЦКИ/-И пишутся через дефис (по-новому, по-русски); наречия с В-/ВО- на -ЫХ/-ИХ — через дефис (во-первых); частицы -то, -либо, -нибудь, кое- — через дефис.',
      };
    }
    return {
      topic: 'Слитное, дефисное и раздельное написание',
      isTrap: Boolean(explicitIsTrap),
      rule: 'Различайте союзы и омонимичные части речи, производные предлоги и существительные, а также дефисные частицы и приставки.',
    };
  }

  if (task === '15') {
    if (expl.includes('исключен') || expl.includes('стеклян') || expl.includes('оловян') || expl.includes('деревян') || expl.includes('ветрен')) {
      return {
        topic: 'Исключения Н и НН в прилагательных',
        isTrap: true,
        rule: 'Исключения с суффиксами -АН-/-ЯН-: стеклянный, оловянный, деревянный (НН). Исключение с суффиксом -ЕН-: ветреный (одна Н), но безветренный (НН).',
      };
    }
    if (expl.includes('кратк') || expl.includes('причасти')) {
      const isShortParticiple = expl.includes('краткое причастие') || ans === 'Н';
      return {
        topic: isShortParticiple ? 'Краткие причастия (всегда одна Н)' : 'Краткие причастия vs краткие прилагательные',
        isTrap: !isShortParticiple,
        rule: 'В кратких причастиях ВСЕГДА пишется одна буква Н (задача решена). В кратких прилагательных пишется столько же Н, сколько в полной форме (девочка умна и воспитанна).',
      };
    }
    if (expl.includes('отглагольн') || expl.includes('приставк') || expl.includes('зависим')) {
      return {
        topic: 'Н и НН в причастиях и отглагольных прилагательных',
        isTrap: Boolean(explicitIsTrap),
        rule: 'Две НН пишутся: 1) есть приставка кроме НЕ-; 2) есть зависимые слова; 3) суффиксы -ОВА-/-ЕВА-; 4) образовано от глагола сов. вида (купленный). Иначе пишется одна Н (жареный, кованый).',
      };
    }
    if (expl.includes('стык') || expl.includes('корень на н')) {
      return {
        topic: 'Стык основы на Н и суффикса -Н-',
        isTrap: false,
        rule: 'На стыке корня на Н и суффикса -Н- всегда пишется две буквы НН (старинный, туманный, осенний, весенний).',
      };
    }
    if (expl.includes('-ин-') || expl.includes('-ан-') || expl.includes('-ян-') || expl.includes('-енн-') || expl.includes('-онн-')) {
      return {
        topic: 'Н и НН в отыменных прилагательных',
        isTrap: false,
        rule: 'Суффиксы -ИН-, -АН-, -ЯН- пишутся с одной Н (глиняный, утиный); суффиксы -ЕНН-, -ОНН- пишутся с двумя НН (соломенный, экскурсионный).',
      };
    }
    return {
      topic: 'Правописание Н и НН в различных частях речи',
      isTrap: Boolean(explicitIsTrap),
      rule: 'Определите часть речи, производящую основу, наличие приставок, зависимых слов и вид исходного глагола.',
    };
  }

  return {
    topic: 'Орфографическое правило ФИПИ',
    isTrap: Boolean(explicitIsTrap),
    rule: 'Проверьте морфему (корень, приставку, суффикс или окончание), в которой находится пропуск.',
  };
}
