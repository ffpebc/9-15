export interface SprintQuestion {
  id: string;
  instanceId?: string;
  kind: 'sprint';
  task: TaskId;
  topic: string;
  rule: string;
  prefix: string;
  suffix: string;
  answer: string;
  options: string[];
  context: string;
  explanation: string;
  source?: string;
  isTrap?: boolean;
}

export interface FipiRow {
  words: [string, string, string] | string[];
  solvedWords: [string, string, string] | string[];
  letter: string;
  isCorrectRow: boolean;
  explanation: string;
}

export interface FipiQuestion {
  id: string;
  instanceId?: string;
  kind: 'fipi';
  task: TaskId;
  topic: string;
  rule: string;
  instruction?: string;
  sentence?: string;
  source?: string;
  rows: FipiRow[];
  correctIndices: number[]; // 1-based indices (e.g., [1, 3])
}

export type TrainerQuestion = SprintQuestion | FipiQuestion;

export interface FlashcardItem {
  id: string;
  task: TaskId;
  badge: string;
  topic: string;
  frontWord: string;
  frontHint: string;
  backWord: string;
  backRule: string;
}

export interface HomophonePairItem {
  id: string;
  task: TaskId;
  topic: string;
  leftWordGap: string;
  leftContext: string;
  leftAns: string;
  rightWordGap: string;
  rightContext: string;
  rightAns: string;
  options: [string, string]; // e.g. ["И / Е", "Е / И"]
  correctOption: string;
  explanation: string;
}

export interface KimVariant {
  id: string;
  title: string;
  tasks: Record<TaskId, FipiQuestion>;
}

export interface TaskMasteryStat {
  solved: number;
  correct: number;
}

