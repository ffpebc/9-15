export function cleanQuestionRule(rule: string | undefined, task: string): string {
  if (task === '15') {
    if (rule) {
      if (/пишется\s+(?:одна\s+буква\s+)?Н(?!Н)/i.test(rule) || /одна\s+буква\s+Н/i.test(rule)) {
        return 'Укажите цифру(-ы), на месте которой(-ых) пишется Н.';
      }
      if (/пишется\s+НН/i.test(rule) || /две\s+буквы\s+НН/i.test(rule)) {
        return 'Укажите цифру(-ы), на месте которой(-ых) пишется НН.';
      }
    }
    return 'Укажите цифру(-ы), на месте которой(-ых) пишется НН (или Н).';
  }
  if (!rule) {
    if (task === '13') return 'Укажите варианты ответов, в которых НЕ с выделенным словом пишется РАЗДЕЛЬНО (или СЛИТНО).';
    return 'Укажите варианты ответов, в которых во всех словах одного ряда пропущена одна и та же буква.';
  }
  let cleaned = rule.replace(/\s*Предложение:\s*«?.*$/is, '').trim();
  cleaned = cleanScraperArtifacts(cleaned).replace(/[«»]/g, '').trim();
  return cleaned || rule;
}

export function resolveTask15Sentence(question: any): string {
  let sent = ((question.sentence || question.instruction || '') as string).trim();

  // If sentence is missing or empty, extract from rule if embedded
  if (!sent && question.rule) {
    const m = question.rule.match(/Предложение:\s*«?(.*)$/is);
    if (m && m[1]) {
      sent = m[1].replace(/»\s*$/, '').trim();
    }
  }

  // Strip scraper artifacts and normalize homoglyphs
  if (sent) {
    sent = cleanScraperArtifacts(sent).replace(/[«»]/g, '').trim();
  }

  const rows = Array.isArray(question.rows) ? question.rows : [];
  const gapDigits = new Set<number>();
  if (sent) {
    const matches = [...sent.matchAll(/([А-Яа-яЁё-]+)\((\d+)\)([А-Яа-яЁё-]*)/g)];
    for (const m of matches) {
      gapDigits.add(parseInt(m[2], 10));
    }
  }

  const hasAllRowGaps =
    rows.length === 0 ||
    Array.from({ length: rows.length }, (_, i) => i + 1).every((d) => gapDigits.has(d));

  // If missing, corrupted, or missing any of the row gap numbers, reconstruct cleanly from question.rows
  if (!sent || !hasAllRowGaps || sent.length < 15) {
    if (rows.length > 0) {
      const parts = rows.map((r: any, i: number) => {
        const raw = (r.words?.[0] || '').replace(/\([Зз]\)/g, '(3)');
        const m = raw.match(/([А-Яа-яЁё-]+)\((\d+)\)([А-Яа-яЁё-]*)/);
        if (m) return `${m[1]}(${m[2]})${m[3]}`;
        const clean = cleanWord(raw);
        if (/\.{2,}|…/.test(clean)) {
          return clean.replace(/\.{2,}|…/, `(${i + 1})`);
        }
        return `${clean}(${i + 1})`;
      });
      sent = `В данном предложении пропущены буквы: ${parts.join(', ')}.`;
    } else {
      sent = 'Укажите цифры на месте пропусков в словах предложения.';
    }
  }

  return sent;
}

export function getTrainerBank() {
  if (cachedQuestionBank) return cachedQuestionBank;

  const sprintQuestions: SprintQuestion[] = [];
  const fipiQuestions: FipiQuestion[] = [];
  const trapQuestions: SprintQuestion[] = [];
  const byId = new Map<string, TrainerQuestion>();

  const seenFipiSignatures = new Set<string>();
  const wordsInAuthenticFipi = new Set<string>();

  // 1. Add authentic whole tasks from FIPI 2026-2027 demo and Shkolkovo (strictly deduplicated)
  if (Array.isArray(PARSED_FIPI_QUESTIONS)) {
    for (const rawFq of PARSED_FIPI_QUESTIONS) {
      if (rawFq.task !== '15' && rawFq.rows.length !== 5) continue;
      if (rawFq.correctIndices.some((c) => c < 1 || c > rawFq.rows.length)) continue;

      let rule = cleanQuestionRule(rawFq.rule, rawFq.task);
      let sentence = rawFq.task === '15' ? resolveTask15Sentence(rawFq) : undefined;

      const rows: FipiRow[] = rawFq.rows.map((r) => ({
        ...r,
        words: r.words.map((w) => (rawFq.task === '15' ? cleanWord(w) : cleanScraperArtifacts(w))),
        solvedWords: r.solvedWords.map((w) => (rawFq.task === '15' ? cleanWord(w) : cleanScraperArtifacts(w))),
        explanation: cleanExplanation(r.explanation),
      }));

      const fq: FipiQuestion = {
        ...rawFq,
        rule,
        instruction: sentence || rawFq.instruction,
        sentence: sentence || (rawFq as any).sentence,
        rows,
      };

      const sig = fq.rows.map((r) => r.words.join('|')).join('||');
      if (seenFipiSignatures.has(sig)) continue;
      seenFipiSignatures.add(sig);
      fipiQuestions.push(fq);
      byId.set(fq.id, fq);
      for (const r of fq.rows) {
        for (const w of r.words) {
          wordsInAuthenticFipi.add(`${fq.task}:${w.toLowerCase().trim()}`);
        }
      }
    }
  }

  // 2. Add unique sprint questions (5000+ unique words) with smart competing options
  const seenSprintKeys = new Set<string>();
  const seenTrapStems = new Set<string>();

  if (Array.isArray(PARSED_SPRINT_QUESTIONS)) {
    for (let i = 0; i < PARSED_SPRINT_QUESTIONS.length; i++) {
      const rawSq = PARSED_SPRINT_QUESTIONS[i];
      if (!rawSq.prefix && rawSq.task !== '13' && rawSq.task !== '14') continue;
      const stemKey = `${rawSq.task}:${rawSq.prefix.toLowerCase().trim()}..${rawSq.suffix.toLowerCase().trim()}`;
      if (seenSprintKeys.has(stemKey)) continue;
      seenSprintKeys.add(stemKey);

      const cleanedContext = cleanScraperArtifacts(rawSq.context);
      const cleanedRule = cleanScraperArtifacts(rawSq.rule);
      const cleanedExplanation = cleanExplanation(rawSq.explanation);

      const classified = classifyWordSubtopicAndException(
        rawSq.task,
        rawSq.prefix,
        rawSq.suffix,
        rawSq.answer,
        cleanedExplanation || cleanedRule,
        cleanedContext,
        Boolean(rawSq.isTrap)
      );

      const smartBaseOpts = getSmartChoiceOptions(
        rawSq.task,
        rawSq.answer,
        rawSq.prefix,
        rawSq.suffix
      );
      const isTrap = Boolean(rawSq.isTrap || classified.isTrap);
      const sq: SprintQuestion = {
        ...rawSq,
        context: cleanedContext,
        explanation: cleanedExplanation,
        topic: classified.topic,
        rule: classified.rule || cleanedRule,
        isTrap,
        options: orderOptionsDeterministically(smartBaseOpts, rawSq.answer, sprintQuestions.length),
      };
      sprintQuestions.push(sq);
      byId.set(sq.id, sq);

      const trapStem = `${sq.task}:${sq.prefix.toLowerCase().trim()}..${sq.suffix.toLowerCase().trim()}`;
      if (isTrap && trapQuestions.length < 120 && !seenTrapStems.has(trapStem)) {
        seenTrapStems.add(trapStem);
        trapQuestions.push(sq);
      }
    }
  }

  // 3. Add any remaining unique items from COMPACT_GROUPS (strictly once per word, never looping!)
  let idx = sprintQuestions.length + 1;
  for (const group of COMPACT_GROUPS) {
    for (const item of group.items) {
      const [prefix, suffix, answer, baseContext, explanation, isTrap] = item;
      const stemKey = `${group.task}:${prefix.toLowerCase().trim()}..${suffix.toLowerCase().trim()}`;
      if (seenSprintKeys.has(stemKey)) continue;
      seenSprintKeys.add(stemKey);

      const classified = classifyWordSubtopicAndException(
        group.task,
        prefix,
        suffix,
        answer,
        explanation,
        baseContext,
        Boolean(isTrap)
      );

      const smartBaseOpts = getSmartChoiceOptions(group.task, answer, prefix, suffix);
      const q: SprintQuestion = {
        id: `sp-${group.task}-${idx++}`,
        kind: 'sprint',
        task: group.task,
        topic: classified.topic,
        rule: classified.rule,
        prefix,
        suffix,
        answer,
        options: orderOptionsDeterministically(smartBaseOpts, answer, sprintQuestions.length),
        context: baseContext,
        explanation,
        isTrap: classified.isTrap,
      };
      sprintQuestions.push(q);
      byId.set(q.id, q);

      const trapStem = `${q.task}:${prefix.toLowerCase().trim()}..${suffix.toLowerCase().trim()}`;
      if (classified.isTrap && trapQuestions.length < 120 && !seenTrapStems.has(trapStem)) {
        seenTrapStems.add(trapStem);
        trapQuestions.push(q);
      }
    }
  }

  if (trapQuestions.length < 30) {
    for (const q of sprintQuestions) {
      if (trapQuestions.length >= 30) break;
      if (!trapQuestions.some((t) => t.id === q.id)) {
        trapQuestions.push(q);
      }
    }
  }

  // 4. Build additional non-overlapping 5-row FIPI tasks from the full unique sprintQuestions pool
  for (const task of TASK_IDS) {
    // Task 15 is strictly authentic sentence questions with numbered gap badges; never synthesize artificial 5x3 row questions
    if (task === '15') continue;

    const taskGroups = COMPACT_GROUPS.filter((g) => g.task === task);
    const taskSprintItems = sprintQuestions.filter((sq) => sq.task === task);

    // Prioritize words that did NOT already appear in authentic PARSED_FIPI_QUESTIONS
    const freshFirst = [
      ...taskSprintItems.filter(
        (w) => !wordsInAuthenticFipi.has(`${task}:${w.prefix.toLowerCase().trim()}..${w.suffix.toLowerCase().trim()}`)
      ),
      ...taskSprintItems.filter((w) =>
        wordsInAuthenticFipi.has(`${task}:${w.prefix.toLowerCase().trim()}..${w.suffix.toLowerCase().trim()}`)
      ),
    ];

    const byAnswer = new Map<string, SprintQuestion[]>();
    for (const it of freshFirst) {
      const list = byAnswer.get(it.answer) || [];
      list.push(it);
      byAnswer.set(it.answer, list);
    }
    let answers = Array.from(byAnswer.keys()).filter(
      (ans) => (byAnswer.get(ans)?.length || 0) >= 15
    );
    if (answers.length < 2) {
      answers = Array.from(byAnswer.keys()).filter(
        (ans) => (byAnswer.get(ans)?.length || 0) >= 1
      );
    }
    if (answers.length < 2) continue;

    const answerCursors = new Map<string, number>();
    for (const ans of answers) answerCursors.set(ans, 0);

    const pickNextFromAnswer = (ans: string): SprintQuestion => {
      const pool = byAnswer.get(ans) || freshFirst;
      const cur = answerCursors.get(ans) || 0;
      const picked = pool[cur % pool.length];
      answerCursors.set(ans, cur + 1);
      return picked;
    };

    const FIPI_PATTERNS: boolean[][] = [
      [true, false, true, false, false],  // 13
      [false, true, false, true, true],   // 245
      [true, true, false, true, false],   // 124
      [false, true, true, false, false],  // 23
      [true, false, false, true, true],   // 145
      [false, false, true, false, true],  // 35
    ];
    const taskOffset = Number(task) - 9;

    for (let setNum = 1; setNum <= 25; setNum++) {
      const rows: FipiRow[] = [];
      const correctIndices: number[] = [];
      const pattern = FIPI_PATTERNS[(setNum + taskOffset * 2) % FIPI_PATTERNS.length];

      for (let r = 0; r < 5; r++) {
        const isCorrectRow = pattern[r];
        const primaryAns = answers[(r + setNum) % answers.length];
        const otherAns = answers[(r + setNum + 1) % answers.length] || primaryAns;

        const w1 = pickNextFromAnswer(primaryAns);
        const w2 = pickNextFromAnswer(primaryAns);
        const w3 = isCorrectRow
          ? pickNextFromAnswer(primaryAns)
          : pickNextFromAnswer(otherAns);

        const formatGap = (w: SprintQuestion) => {
          if (task === '13' || task === '14') {
            return `${w.prefix} ${w.suffix} ${w.context}`.trim();
          }
          return w.context ? `${w.prefix}..${w.suffix} (${w.context})` : `${w.prefix}..${w.suffix}`;
        };
        const formatSolved = (w: SprintQuestion) => {
          if (task === '13' || task === '14') {
            if (w.answer === 'СЛИТНО') {
              return `${w.prefix.replace(/[()]/g, '')}${w.suffix} (${w.context})`;
            } else if (w.answer === 'ДЕФИСНО') {
              return `${w.prefix.replace(/[()]/g, '')}-${w.suffix} (${w.context})`;
            } else {
              return `${w.prefix.replace(/[()]/g, '')} ${w.suffix} (${w.context})`;
            }
          }
          return `${w.prefix}${w.answer.toLowerCase()}${w.suffix}`;
        };

        rows.push({
          words: [formatGap(w1), formatGap(w2), formatGap(w3)],
          solvedWords: [formatSolved(w1), formatSolved(w2), formatSolved(w3)],
          letter: primaryAns,
          isCorrectRow,
          explanation: `${formatSolved(w1)}, ${formatSolved(w2)}, ${formatSolved(w3)}`,
        });

        if (isCorrectRow) {
          correctIndices.push(r + 1);
        }
      }

      const fq: FipiQuestion = {
        id: `fipi-${task}-${setNum}`,
        kind: 'fipi',
        task,
        topic: TASK_META[task].title,
        rule: taskGroups[0]?.rule || '',
        rows,
        correctIndices,
      };
      const sig = fq.rows.map((r) => r.words.join('|')).join('||');
      if (!seenFipiSignatures.has(sig)) {
        seenFipiSignatures.add(sig);
        fipiQuestions.push(fq);
        byId.set(fq.id, fq);
      }
    }
  }

  // Build 35 full authentic KIM Variants (each containing 1 FipiQuestion for tasks 9, 10, 11, 12, 13, 14, 15)
  const kimVariants: KimVariant[] = [];
  for (let v = 1; v <= 35; v++) {
    const tasksMap = {} as Record<TaskId, FipiQuestion>;
    for (const t of TASK_IDS) {
      const authenticList = PARSED_TASKS_MAP?.[t] || [];
      if (authenticList.length >= v) {
        tasksMap[t] = authenticList[v - 1];
      } else {
        const fipiForTask = fipiQuestions.filter((fq) => fq.task === t);
        if (fipiForTask.length > 0) {
          tasksMap[t] = fipiForTask[(v - 1) % fipiForTask.length];
        } else if (fipiQuestions.length > 0) {
          tasksMap[t] = { ...fipiQuestions[0], task: t, topic: TASK_META[t].title };
        }
      }
    }
    const variantTitle =
      v === 1
        ? 'Вариант КИМ № 1 (ФИПИ 2026–2027 Демоверсия)'
        : v === 2
        ? 'Вариант КИМ № 2 (ФИПИ 2025 Демоверсия)'
        : `Вариант КИМ № ${v} (Дощинский-2026 / ФИПИ)`;

    kimVariants.push({
      id: `kim-var-${v}`,
      title: variantTitle,
      tasks: tasksMap,
    });
  }

  cachedQuestionBank = {
    sprintQuestions,
    fipiQuestions,
    trapQuestions,
    kimVariants,
    byId,
  };
  return cachedQuestionBank;
}

