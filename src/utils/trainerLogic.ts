export function buildWorkoutQueue(
  quantities: Record<TaskId, number>,
  mode: WorkoutMode,
  options?: { randomize?: boolean; shuffleTasks?: boolean }
): TrainerQuestion[] {
  const bank = getTrainerBank();
  const queue: TrainerQuestion[] = [];
  const randomize = options?.randomize !== false;

  const sessionUsedWordStems = new Set<string>();
  const sessionUsedQuestionIds = new Set<string>();

  for (const task of TASK_IDS) {
    const count = clampTaskQty(quantities[task] || 0);
    if (count <= 0) continue;

    const rawSprintPool = bank.sprintQuestions.filter((q) => q.task === task);
    const rawFipiPool = bank.fipiQuestions.filter((q) => q.task === task);

    const sprintNeed =
      mode === 'sprint'
        ? count
        : mode === 'fipi'
        ? 0
        : count - Math.floor((count + 1) / 3);
    const fipiNeed = count - sprintNeed;

    // Reset cross-session tracker if fewer than needed unseen items remain
    if (
      randomize &&
      rawSprintPool.length - recentSprintIdsByTask[task].size < sprintNeed
    ) {
      recentSprintIdsByTask[task].clear();
    }
    if (
      randomize &&
      rawFipiPool.length - recentFipiIdsByTask[task].size < fipiNeed
    ) {
      recentFipiIdsByTask[task].clear();
    }

    // 1. Pick non-overlapping FIPI questions first (since 1 FIPI question contains 15 words)
    const pickedFipi: FipiQuestion[] = [];
    if (fipiNeed > 0) {
      const candidates = randomize
        ? [
            ...shuffleArray(rawFipiPool.filter((q) => !recentFipiIdsByTask[task].has(q.id))),
            ...shuffleArray(rawFipiPool.filter((q) => recentFipiIdsByTask[task].has(q.id))),
          ]
        : rawFipiPool;

      // Pass A: Pick tasks whose words have zero overlap with anything used in this session
      for (const fq of candidates) {
        if (pickedFipi.length >= fipiNeed) break;
        if (sessionUsedQuestionIds.has(fq.id)) continue;
        const words = fq.rows.flatMap((r) =>
          r.words.map((w) => `${task}:${w.toLowerCase().replace(/\([^)]*\)/g, '').trim()}`)
        );
        const hasWordOverlap = words.some((w) => sessionUsedWordStems.has(w));
        if (!hasWordOverlap) {
          pickedFipi.push(fq);
          sessionUsedQuestionIds.add(fq.id);
          if (randomize) recentFipiIdsByTask[task].add(fq.id);
          for (const w of words) sessionUsedWordStems.add(w);
        }
      }

      // Pass B: If zero-overlap tasks are exhausted, pick tasks without ID duplicates
      if (pickedFipi.length < fipiNeed) {
        for (const fq of candidates) {
          if (pickedFipi.length >= fipiNeed) break;
          if (!sessionUsedQuestionIds.has(fq.id)) {
            pickedFipi.push(fq);
            sessionUsedQuestionIds.add(fq.id);
            if (randomize) recentFipiIdsByTask[task].add(fq.id);
            for (const r of fq.rows) {
              for (const w of r.words) {
                sessionUsedWordStems.add(`${task}:${w.toLowerCase().replace(/\([^)]*\)/g, '').trim()}`);
              }
            }
          }
        }
      }
    }

    // 2. Pick non-overlapping Sprint questions (strictly 0 repeats in session)
    const pickedSprint: SprintQuestion[] = [];
    if (sprintNeed > 0) {
      const candidates = randomize
        ? [
            ...shuffleArray(rawSprintPool.filter((q) => !recentSprintIdsByTask[task].has(q.id))),
            ...shuffleArray(rawSprintPool.filter((q) => recentSprintIdsByTask[task].has(q.id))),
          ]
        : rawSprintPool;

      for (const sq of candidates) {
        if (pickedSprint.length >= sprintNeed) break;
        if (sessionUsedQuestionIds.has(sq.id)) continue;
        const stem = `${sq.task}:${sq.prefix.toLowerCase().trim()}..${sq.suffix.toLowerCase().trim()}`;
        if (sessionUsedWordStems.has(stem)) continue;
        pickedSprint.push(sq);
        sessionUsedQuestionIds.add(sq.id);
        if (randomize) recentSprintIdsByTask[task].add(sq.id);
        sessionUsedWordStems.add(stem);
      }

      // Fallback only if bank doesn't have enough unseen stems (unlikely with 1000+ words)
      if (pickedSprint.length < sprintNeed) {
        for (const sq of candidates) {
          if (pickedSprint.length >= sprintNeed) break;
          if (!sessionUsedQuestionIds.has(sq.id)) {
            pickedSprint.push(sq);
            sessionUsedQuestionIds.add(sq.id);
            if (randomize) recentSprintIdsByTask[task].add(sq.id);
          }
        }
      }
    }

    const balancedSprint = balanceSprintQuestionsList(pickedSprint);

    // 3. Assemble and interleave questions for this task
    let sIdx = 0;
    let fIdx = 0;
    for (let i = 0; i < count; i++) {
      const useFipi = mode === 'fipi' || (mode === 'mixed' && i % 3 === 2);
      if (useFipi && fIdx < pickedFipi.length) {
        const item = pickedFipi[fIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (sIdx < balancedSprint.length) {
        const item = balancedSprint[sIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (fIdx < pickedFipi.length) {
        const item = pickedFipi[fIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      } else if (sIdx < balancedSprint.length) {
        const item = balancedSprint[sIdx++];
        queue.push({
          ...item,
          instanceId: `${item.id}-run-${queue.length + 1}-${Math.random().toString(36).slice(2, 7)}`,
        });
      }
    }
  }

  if (randomize && options?.shuffleTasks) {
    return shuffleArray(queue);
  }

  return queue;
}

export function applyAnswerToState(
  state: TrainerState,
  question: TrainerQuestion,
  isCorrect: boolean,
  userChoiceLabel: string,
  isSprintTab = false
): TrainerState {
  const task = question.task;
  const prevTaskStat = state.taskStats[task] || { solved: 0, correct: 0 };
  const updatedTaskStats: Record<TaskId, TaskMasteryStat> = {
    ...state.taskStats,
    [task]: {
      solved: prevTaskStat.solved + 1,
      correct: prevTaskStat.correct + (isCorrect ? 1 : 0),
    },
  };

  let updatedErrorBank = [...state.errorBank];
  if (!isCorrect) {
    const entry: ErrorBankEntry =
      question.kind === 'sprint'
        ? {
            id: `err-${question.id}`,
            task: question.task,
            topic: question.topic,
            wordDisplay:
              question.task === '13'
                ? `${question.prefix} ${question.suffix}`
                : question.task === '14'
                ? `${question.prefix} ${question.suffix}`
                : `${question.prefix}..${question.suffix}`,
            correctWord:
              question.task === '13'
                ? question.answer === 'СЛИТНО'
                  ? `${question.prefix.replace(/[()]/g, '')}${question.suffix}`
                  : `${question.prefix.replace(/[()]/g, '')} ${question.suffix}`
                : question.task === '14'
                ? formatTask14SolvedWord(question.prefix, question.suffix, question.answer)
                : `${question.prefix}${question.answer.toLowerCase()}${question.suffix}`,
            userChoice: userChoiceLabel,
            correctChoice: question.answer,
            context: question.context,
            explanation: question.explanation,
            rule: question.rule,
            timestamp: Date.now(),
            questionId: question.id,
          }
        : {
            id: `err-${question.id}`,
            task: question.task,
            topic: question.topic,
            wordDisplay: `Задание № ${question.task} · 5 строк ФИПИ`,
            correctWord: `Задание № ${question.task} (5 строк)`,
            userChoice: userChoiceLabel,
            correctChoice: question.correctIndices.join(''),
            context: `Подходят строки: ${question.correctIndices.join(', ')}`,
            explanation: question.rows
              .map((r, idx) =>
                r.isCorrectRow
                  ? `Строка ${idx + 1} (${r.letter}): ${r.solvedWords.join(', ')}`
                  : null
              )
              .filter(Boolean)
              .join(' | '),
            rule: question.rule,
            timestamp: Date.now(),
            questionId: question.id,
          };

    updatedErrorBank = [
      entry,
      ...updatedErrorBank.filter((e) => e.questionId !== question.id),
    ].slice(0, 100);
  } else {
    updatedErrorBank = updatedErrorBank.filter((e) => e.questionId !== question.id);
  }

  const nextStreak = isSprintTab
    ? isCorrect
      ? state.sprintStreak + 1
      : 0
    : isCorrect
    ? state.sprintStreak + 1
    : 0;
  const nextBestStreak = Math.max(state.bestStreak || 0, nextStreak);

  return {
    ...state,
    totalSolved: state.totalSolved + 1,
    totalCorrect: state.totalCorrect + (isCorrect ? 1 : 0),
    sprintStreak: nextStreak,
    bestStreak: nextBestStreak,
    sprintTotal: isSprintTab ? state.sprintTotal + 1 : state.sprintTotal,
    sprintCorrect: isSprintTab
      ? state.sprintCorrect + (isCorrect ? 1 : 0)
      : state.sprintCorrect,
    taskStats: updatedTaskStats,
    errorBank: updatedErrorBank,
  };
}

